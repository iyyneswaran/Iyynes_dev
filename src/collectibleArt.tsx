export function KeepsakeIcon({
  id,
  size = 40,
}: {
  id: KeepsakeId;
  size?: number;
}) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 21 22"
      shapeRendering="crispEdges"
      aria-hidden="true"
    >
      {artwork[id].map(([fill, x, y, w, h], i) => (
        <rect key={i} fill={fill} x={x} y={y} width={w} height={h} />
      ))}
    </svg>
  );
}
export function drawKeepsake(ctx: CanvasRenderingContext2D, id: KeepsakeId) {
  for (const [fill, x, y, w, h] of artwork[id]) {
    ctx.fillStyle = fill;
    ctx.fillRect(x, y, w, h);
  }
}
